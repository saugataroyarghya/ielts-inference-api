"""Export uv's locked runtime dependencies for BentoML; never resolve a second dependency set."""

import argparse
import subprocess
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for profile, extras in [("cpu", ["cpu"]), ("gpu", ["cuda", "asr"])]:
        export_profile(profile, extras, args.check)
    settings = tomllib.loads((ROOT / "pyproject.toml").read_text())
    content = "\n".join(settings["tool"]["uv"]["override-dependencies"]) + "\n"
    path = ROOT / "requirements-overrides.txt"
    if args.check:
        if not path.exists() or path.read_text() != content:
            raise SystemExit("requirements-overrides.txt is stale; run scripts.export_requirements")
    else:
        path.write_text(content)


def export_profile(profile: str, extras: list[str], check: bool):
    exported = subprocess.check_output(
        [
            "uv",
            "export",
            "--locked",
            "--no-dev",
            "--no-emit-project",
            "--no-emit-package",
            "bentoml",
            "--no-hashes",
            "--no-annotate",
            "--no-header",
            *[flag for extra in extras for flag in ("--extra", extra)],
        ],
        cwd=ROOT,
        text=True,
    )
    # BentoML injects its own exact version; both profiles use the same uv.lock.
    backend = "cpu" if profile == "cpu" else "cu128"
    content = (
        "# Generated by uv run python -m scripts.export_requirements; do not edit.\n"
        f"--find-links https://download.pytorch.org/whl/{backend}/torch/\n"
        + (
            f"--find-links https://download.pytorch.org/whl/{backend}/torchvision/\n"
            if profile == "gpu"
            else ""
        )
        + exported
    )
    path = ROOT / ("requirements.txt" if profile == "cpu" else "requirements-gpu.txt")
    if check:
        if not path.exists() or path.read_text() != content:
            raise SystemExit(f"{path.name} is stale; run scripts.export_requirements.")
        print(f"{path.name} matches uv.lock")
    else:
        path.write_text(content)
        print(f"Exported {path.name}")


if __name__ == "__main__":
    main()
